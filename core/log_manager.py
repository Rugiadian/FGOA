"""
Log Management and Crash Cleanup Module for FGOA.
Parses, categorizes, archives, and cleans crash reports based on signature and resolution status.
"""
import os
import re
import datetime
from typing import List, Dict, Tuple, Any

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CRASH_LOG_PATH = os.path.join(BASE_DIR, "fgoa_crash.log")
HISTORY_DIR = os.path.join(BASE_DIR, "history")


class CrashEntry:
    def __init__(self, raw_text: str):
        self.raw_text = raw_text.strip()
        self.timestamp = ""
        self.version = ""
        self.error_type = ""
        self.error_message = ""
        self.stack_trace = ""
        self.last_file = ""
        self.last_line = 0
        self.last_func = ""
        self._parse()

    def _parse(self):
        m_time = re.search(r"\[FGOA CRASH REPORT\s*-\s*([^\]]+)\]", self.raw_text)
        if m_time:
            self.timestamp = m_time.group(1).strip()

        m_ver = re.search(r"FGOA Version:\s*([^\r\n]+)", self.raw_text)
        if m_ver:
            self.version = m_ver.group(1).strip()

        m_type = re.search(r"Error Type:\s*([^\r\n]+)", self.raw_text)
        if m_type:
            self.error_type = m_type.group(1).strip()

        m_msg = re.search(r"Error Message:\s*([^\r\n]+)", self.raw_text)
        if m_msg:
            self.error_message = m_msg.group(1).strip()

        m_tb = re.search(r"Stack Trace:\s*\n(.*)", self.raw_text, re.DOTALL)
        if m_tb:
            self.stack_trace = m_tb.group(1).strip()

        # Find the last frame in stack trace
        tb_frames = re.findall(r'File "([^"]+)", line (\d+), in (\w+)', self.stack_trace)
        if tb_frames:
            fpath, line_no, func_name = tb_frames[-1]
            self.last_file = os.path.basename(fpath)
            self.last_line = int(line_no)
            self.last_func = func_name

    @property
    def is_synthetic_test(self) -> bool:
        """Returns True if the crash is an intentional error from test suites."""
        if "tests\\" in self.stack_trace or "tests/" in self.stack_trace:
            return True
        if "SyntheticKey_" in self.error_message or "Test Synthetic Error" in self.error_message:
            return True
        return False

    @property
    def signature(self) -> str:
        """Returns a unique signature for deduplication and matching."""
        return f"{self.error_type}::{self.last_file}::{self.last_func}"


def parse_crash_log(file_path: str = CRASH_LOG_PATH) -> List[CrashEntry]:
    """Parse crash log into a list of CrashEntry objects."""
    if not os.path.exists(file_path):
        return []

    with open(file_path, "r", encoding="utf-8", errors="ignore") as f:
        content = f.read()

    blocks = content.split("=" * 70)
    entries = []
    for b in blocks:
        if "[FGOA CRASH REPORT" in b:
            entry = CrashEntry(b)
            entries.append(entry)
    return entries


def classify_crashes(entries: List[CrashEntry]) -> Dict[str, List[CrashEntry]]:
    """
    Classify crash entries into:
    - synthetic_test: Generated by test suites
    - resolved: Known resolved bugs verified against the current codebase
    - unresolved: Active or unaddressed bugs in the current codebase
    """
    # Known resolved bug signatures that have been verified as fixed in current codebase:
    KNOWN_RESOLVED_SIGNATURES = {
        "AttributeError::condition_editor_dialog.py::_on_nudge_point",
        "AttributeError::coordinate_picker_dialog.py::set_image",
        "AttributeError::inspector_widget.py::_on_edit_action",
        "AttributeError::screen_capture.py::capture_client_area",
        "NameError::inspector_widget.py::_on_node_snapshot_clicked",
        "AttributeError::main_window.py::_on_open_anti_ban_dialog",
        "AttributeError::preset_dialog.py::_init_ui",
    }

    result = {
        "synthetic_test": [],
        "resolved": [],
        "unresolved": []
    }

    for entry in entries:
        if entry.is_synthetic_test:
            result["synthetic_test"].append(entry)
        elif entry.signature in KNOWN_RESOLVED_SIGNATURES:
            result["resolved"].append(entry)
        else:
            result["unresolved"].append(entry)

    return result


def archive_and_clean_crash_log(
    file_path: str = CRASH_LOG_PATH,
    history_dir: str = HISTORY_DIR
) -> Dict[str, Any]:
    """
    Backs up the entire crash log to history/archive,
    and rewrites fgoa_crash.log containing ONLY unresolved crashes.
    """
    if not os.path.exists(file_path):
        return {"status": "no_file", "unresolved_count": 0}

    entries = parse_crash_log(file_path)
    if not entries:
        return {"status": "empty", "unresolved_count": 0}

    classification = classify_crashes(entries)
    unresolved = classification["unresolved"]
    resolved = classification["resolved"]
    synthetic = classification["synthetic_test"]

    # 1. Create backup archive in history
    os.makedirs(history_dir, exist_ok=True)
    timestamp_str = datetime.datetime.now().strftime("%Y%m%d_%H%M%S")
    archive_filename = f"fgoa_crash_backup_{timestamp_str}.log"
    archive_path = os.path.join(history_dir, archive_filename)

    with open(file_path, "r", encoding="utf-8", errors="ignore") as src, \
         open(archive_path, "w", encoding="utf-8") as dst:
        dst.write(src.read())

    # 2. Rewrite fgoa_crash.log with unresolved crashes only
    with open(file_path, "w", encoding="utf-8") as f:
        if unresolved:
            for entry in unresolved:
                f.write(f"{'='*70}\n")
                f.write(entry.raw_text)
                f.write(f"\n{'='*70}\n\n")
        else:
            f.write("# [FGOA CRASH LOG - ALL REPORTED ISSUES RESOLVED]\n")

    return {
        "status": "success",
        "total_count": len(entries),
        "synthetic_count": len(synthetic),
        "resolved_count": len(resolved),
        "unresolved_count": len(unresolved),
        "archive_path": archive_path,
        "unresolved_signatures": [e.signature for e in unresolved]
    }


if __name__ == "__main__":
    res = archive_and_clean_crash_log()
    print("Crash Log Cleanup Result:")
    print(f"- Total Reports Parsed: {res.get('total_count')}")
    print(f"- Test Synthetic Reports Cleaned: {res.get('synthetic_count')}")
    print(f"- Resolved Bug Reports Cleaned: {res.get('resolved_count')}")
    print(f"- Unresolved Active Reports Retained: {res.get('unresolved_count')}")
    print(f"- Backup Archive: {res.get('archive_path')}")
    print(f"- Unresolved Signatures: {res.get('unresolved_signatures')}")
